-- 初登校日（2026-04-08）の朝、教官の机に花を添えた手紙が置かれていた。
-- テーブル名・列名・データはすべて日本語。文字列は N'...' を付けること（付けないと文字化けする）
--
-- 人物IDの決まり: 職員は 1〜、学生は 100〜（入退室記録の人物IDは、どちらの名簿とも突き合わせられる）
--
-- アプリから渡されるパラメーター（SqlParameter なので、名前に記号が入っていても安全）:
--   @PlayerId   プレイヤーの学生ID（100 固定）
--   @PlayerName プレイヤーの名前

-- 職員の名簿
CREATE TABLE 職員名簿 (
    職員ID INT           NOT NULL PRIMARY KEY,
    名前   NVARCHAR(50)  NOT NULL,
    種族   NVARCHAR(30)  NULL,
    役職   NVARCHAR(10)  NOT NULL,      -- 教官 / 門番 / 事務員
    見た目 NVARCHAR(100) NULL,
    備考   NVARCHAR(200) NULL
);
GO

-- 学生（見習い）の名簿
CREATE TABLE 学生名簿 (
    学生ID INT           NOT NULL PRIMARY KEY,
    名前   NVARCHAR(50)  NOT NULL,
    種族   NVARCHAR(30)  NULL,
    見た目 NVARCHAR(100) NULL,
    備考   NVARCHAR(200) NULL
);
GO

-- 実習室の正門ゲートの入退室記録。人物ID は 職員ID または 学生ID
CREATE TABLE 入退室記録 (
    記録ID INT IDENTITY(1,1) PRIMARY KEY,
    人物ID INT           NOT NULL,
    区分   NVARCHAR(2)   NOT NULL CHECK (区分 IN (N'入室', N'退室')),
    日時   DATETIME2(0)  NOT NULL
);
GO

-- 出席簿（点呼の結果。学生のみ）
CREATE TABLE 出席簿 (
    学生ID INT           NOT NULL REFERENCES 学生名簿(学生ID),
    授業日 DATE          NOT NULL,
    出欠   NVARCHAR(2)   NOT NULL CHECK (出欠 IN (N'出席', N'欠席')),
    PRIMARY KEY (学生ID, 授業日)
);
GO

-- 教官の机に仕込まれた魔導センサーの記録（物体の出現と、近づいた魔力）
CREATE TABLE 机の魔力記録 (
    記録ID       INT           NOT NULL PRIMARY KEY,
    日時         DATETIME2(0)  NOT NULL,
    内容         NVARCHAR(60)  NOT NULL,
    近接した魔力 NVARCHAR(20)  NULL
);
GO

