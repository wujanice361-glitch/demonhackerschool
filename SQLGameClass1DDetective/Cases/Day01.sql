-- Day 1: 教官への贈り物
-- 初登校日の朝、教官の机に花を添えた手紙が置かれていた。
-- テーブル名・列名・データはすべて日本語。文字列は N'...' を付けること（付けないと文字化けする）
--
-- 人物IDの決まり: 職員は 1〜、学生は 101〜（入退室記録の人物IDは、どちらの名簿とも突き合わせられる）
--
-- アプリから渡されるパラメーター（SqlParameter なので、名前に記号が入っていても安全）:
--   @PlayerId   プレイヤーの学生ID（107 固定）
--   @PlayerName プレイヤーの名前
--   @PlayerNote プレイヤーの自己紹介（名簿の備考に入れる）

-- 職員の名簿
CREATE TABLE 職員名簿 (
    職員ID INT           NOT NULL PRIMARY KEY,
    名前   NVARCHAR(50)  NOT NULL,
    種族   NVARCHAR(30)  NULL,
    役職   NVARCHAR(10)  NOT NULL,      -- 教官 / 門番
    見た目 NVARCHAR(100) NULL,
    備考   NVARCHAR(200) NULL
);
GO

-- 学生（見習い）の名簿
CREATE TABLE 学生名簿 (
    学生ID INT           NOT NULL PRIMARY KEY,
    名前   NVARCHAR(50)  NOT NULL,
    種族   NVARCHAR(30)  NULL,          -- ネムだけ記載なし（後の伏線）
    見た目 NVARCHAR(100) NULL,
    備考   NVARCHAR(200) NULL
);
GO

-- 実習室の入退室記録（魔力紋の認証ログ）。人物ID は 職員ID または 学生ID
CREATE TABLE 入退室記録 (
    記録ID INT IDENTITY(1,1) PRIMARY KEY,
    人物ID INT           NOT NULL,
    区分   NVARCHAR(2)   NOT NULL CHECK (区分 IN (N'入室', N'退室')),
    日時   DATETIME2(0)  NOT NULL
);
GO

-- 出席簿（点呼の結果。学生のみ）
CREATE TABLE 出席簿 (
    学生ID INT           NOT NULL REFERENCES 学生名簿(学生ID),
    授業日 DATE          NOT NULL,
    出欠   NVARCHAR(2)   NOT NULL CHECK (出欠 IN (N'出席', N'欠席')),
    PRIMARY KEY (学生ID, 授業日)
);
GO

