IF OBJECT_ID(N'dbo.提出書類記録') IS NOT NULL DROP TABLE dbo.提出書類記録;
GO

CREATE TABLE 提出書類記録 (
    書類ID   INT           NOT NULL PRIMARY KEY,
    提出者ID INT           NOT NULL,           -- 学生ID
    書類名   NVARCHAR(30)  NOT NULL,
    サイン数 INT           NOT NULL,
    審査結果 NVARCHAR(10)  NOT NULL,
    却下回数 INT           NOT NULL,
    承認者ID INT           NULL,               -- 職員ID（1=ホネスト、3=オルガ）
    備考     NVARCHAR(100) NULL
);
GO

